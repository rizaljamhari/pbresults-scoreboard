import { randomUUID } from "node:crypto";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { bestOfFromNotes, scheduledGameSchema, type ParsedSchedule, type ScheduledGame } from "../shared/matchList.js";

/**
 * Reads a schedule PDF from the Malaysia Paintball Hub tournament system: a table of #, Game ID, Time, Min, Division,
 * Stage, Home, Away and Notes, where long names wrap onto extra lines inside their cell. Text is placed by position:
 * the header row gives each column's left edge, and a row starts where the # column has a number.
 */

export class SchedulePdfError extends Error {}

type TextItem = { x: number; y: number; text: string };
type Column = "index" | "gameId" | "time" | "minutes" | "division" | "stage" | "home" | "away" | "notes";

const headerColumns: Array<[string, Column]> = [
  ["#", "index"],
  ["GAME", "gameId"],
  ["TIME", "time"],
  ["MIN", "minutes"],
  ["DIVISION", "division"],
  ["STAGE", "stage"],
  ["HOME", "home"],
  ["AWAY", "away"],
  ["NOTES", "notes"]
];

/** Text a few points above a row's first line (notes sit slightly higher) still belongs to that row. */
const ROW_TOLERANCE = 4;
/** Wrapped lines inside a cell sit 7 to 9 points apart; a bigger gap starts something else. */
const LINE_GAP = 12;
const generatedNote = /generated by guided quick generation\.?/gi;
const dateLine = /^(monday|tuesday|wednesday|thursday|friday|saturday|sunday),\s+\d{1,2}\s+\w+\s+\d{4}$/i;

async function readPages(buffer: Buffer): Promise<TextItem[][]> {
  let doc;
  try {
    doc = await getDocument({ data: new Uint8Array(buffer), isEvalSupported: false, useSystemFonts: false, verbosity: 0 }).promise;
  } catch {
    throw new SchedulePdfError("This file could not be opened as a PDF.");
  }
  try {
    const pages: TextItem[][] = [];
    for (let number = 1; number <= doc.numPages; number += 1) {
      const page = await doc.getPage(number);
      const content = await page.getTextContent();
      const items: TextItem[] = [];
      for (const item of content.items) {
        if (!("str" in item) || !item.str.trim()) continue;
        items.push({ x: item.transform[4], y: item.transform[5], text: item.str.trim() });
      }
      pages.push(items);
    }
    return pages;
  } finally {
    await doc.destroy();
  }
}

/** Each column's left edge: halfway between its header and the previous one, since cells start left of their header. */
function findColumns(items: TextItem[]): { headerY: number; edges: Array<[number, Column]> } | null {
  const home = items.find((item) => item.text === "HOME");
  if (!home) return null;
  const onHeader = (label: string) => items.find((item) => item.text === label && Math.abs(item.y - home.y) <= 8);
  const found = headerColumns.map(([label, column]) => [onHeader(label), column] as const);
  if (found.some(([item]) => !item)) return null;
  const edges: Array<[number, Column]> = found.map(([item, column], index) => {
    const previous = index > 0 ? found[index - 1][0]! : null;
    return [previous ? (previous.x + item!.x) / 2 : -Infinity, column];
  });
  return { headerY: Math.min(...found.map(([item]) => item!.y)), edges };
}

function columnAt(x: number, edges: Array<[number, Column]>): Column {
  let column = edges[0][1];
  for (const [edge, name] of edges) if (x >= edge) column = name;
  return column;
}

/** Joins a cell's wrapped lines: "COMRADES OF" + "DARKNESS “COD”", or "Quarter-" + "Final winner" without a space. */
function joinLines(lines: string[]) {
  return lines.reduce((text, line) => (!text ? line : /\w-$/.test(text) ? `${text}${line}` : `${text} ${line}`), "");
}

function cleanNotes(text: string) {
  // The tournament system's own notes: how the row was made, internal stage ids, seeding sources and repairs.
  const cleaned = text
    .replace(generatedNote, "")
    .replace(/stage break:\s*\S+/gi, "")
    .replace(/schedule stage:.*?(?=home source:|away source:|repaired by|$)/gi, "")
    .replace(/(home|away) source:\s*\S+/gi, "")
    .replace(/repaired by\s*\S+/gi, "")
    .replace(/\s+/g, " ")
    .trim();
  return cleaned === "—" || cleaned === "-" ? "" : cleaned.slice(0, 200);
}

function readTitle(firstPage: TextItem[]): { title: string; date: string } {
  const date = firstPage.find((item) => dateLine.test(item.text))?.text ?? "";
  const heading = firstPage.find((item) => /^O\s*F\s*F\s*I\s*C\s*I\s*A\s*L/i.test(item.text));
  if (!heading) return { title: "", date };
  // The event name: the left-hand lines under "OFFICIAL TOURNAMENT SCHEDULE", down to "All Divisions".
  const end = firstPage.find((item) => item.text === "All Divisions" && item.y < heading.y)?.y ?? heading.y - 80;
  const lines = firstPage
    .filter((item) => item.x < heading.x + 20 && item.y < heading.y && item.y > end)
    .sort((a, b) => b.y - a.y)
    .map((item) => item.text);
  return { title: joinLines(lines).trim(), date };
}

export async function parseSchedulePdf(buffer: Buffer): Promise<ParsedSchedule> {
  const pages = await readPages(buffer);
  const games: ScheduledGame[] = [];
  const warnings: string[] = [];
  let tablesFound = 0;

  for (const items of pages) {
    const columns = findColumns(items);
    if (!columns) continue;
    tablesFound += 1;
    const body = items.filter((item) => item.y < columns.headerY - 2);
    const placed = body.map((item) => ({ ...item, column: columnAt(item.x, columns.edges) }));

    // A row starts at a number in the # column with a time beside it.
    const starts = placed
      .filter((item) => item.column === "index" && /^\d+$/.test(item.text))
      .filter((start) => placed.some((item) => item.column === "time" && Math.abs(item.y - start.y) <= 2 && /^\d{1,2}:\d{2}$/.test(item.text)))
      .sort((a, b) => b.y - a.y);

    starts.forEach((start, index) => {
      const top = start.y + ROW_TOLERANCE;
      const bottom = index + 1 < starts.length ? starts[index + 1].y + ROW_TOLERANCE : -Infinity;
      // A cell is its first line beside the row number plus the lines that follow on closely. Anything further down
      // (the page footer under the last row) is not part of it.
      const cells = new Map<Column, { texts: string[]; lastY: number }>();
      placed
        .filter((item) => item.y <= top && item.y > bottom)
        .sort((a, b) => b.y - a.y || a.x - b.x)
        .forEach((item) => {
          const current = cells.get(item.column);
          if (!current) {
            if (Math.abs(item.y - start.y) <= ROW_TOLERANCE) cells.set(item.column, { texts: [item.text], lastY: item.y });
          } else if (current.lastY - item.y <= LINE_GAP) {
            current.texts.push(item.text);
            current.lastY = item.y;
          }
        });
      const cell = (column: Column) => joinLines(cells.get(column)?.texts ?? []);

      const gameIdText = cell("gameId");
      const isBreak = !/^\d+$/.test(gameIdText);
      const notes = cleanNotes(cell("notes"));
      const minutes = Number.parseInt(cell("minutes"), 10);
      const game = scheduledGameSchema.parse({
        id: randomUUID(),
        gameId: isBreak ? null : Number(gameIdText),
        time: cell("time"),
        minutes: Number.isFinite(minutes) ? minutes : null,
        division: cell("division").slice(0, 60),
        stage: cell("stage").slice(0, 80),
        kind: isBreak ? "break" : "game",
        // A break's "home" cell holds its description ("Lunch Break"), which reads better as its note.
        home: { label: isBreak ? "" : cell("home").slice(0, 80) },
        away: { label: isBreak ? "" : cell("away").slice(0, 80) },
        bestOf: isBreak ? 1 : bestOfFromNotes(notes),
        notes: isBreak ? [cell("home"), notes].filter(Boolean).join(" · ").slice(0, 200) : notes
      });
      if (!isBreak && (!game.home.label || !game.away.label)) warnings.push(`Game ${game.gameId} is missing a team name.`);
      games.push(game);
    });
  }

  if (tablesFound === 0 || games.length === 0) {
    throw new SchedulePdfError("This PDF doesn't look like a Malaysia Paintball Hub schedule. No schedule table was found.");
  }
  return { ...readTitle(pages[0] ?? []), games, warnings };
}
